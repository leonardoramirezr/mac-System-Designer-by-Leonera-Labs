// Regenerates web/js/icons.js with the subset of Lucide icons the app uses.
// Usage: npm install && npm run icons
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

require(join(root, 'web/js/catalog.js'));
const { catalog } = globalThis.SD;

const lucide = JSON.parse(readFileSync(require.resolve('@iconify-json/lucide/icons.json'), 'utf8'));
const info = JSON.parse(readFileSync(require.resolve('@iconify-json/lucide/info.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(require.resolve('@iconify-json/lucide/package.json'), 'utf8'));

const names = new Set([
  ...catalog.types.map((t) => t.icon),
  ...catalog.groupKinds.map((k) => k.icon),
  ...catalog.uiIcons,
]);

const bodies = {};
const missing = [];
for (const name of [...names].sort()) {
  const alias = lucide.aliases && lucide.aliases[name];
  const icon = lucide.icons[name] || (alias && lucide.icons[alias.parent]);
  if (!icon) missing.push(name);
  else bodies[name] = icon.body;
}
if (missing.length) {
  console.error('Missing Lucide icons:', missing.join(', '));
  process.exit(1);
}

const out = `// Generated by scripts/build-icons.mjs — do not edit by hand.
// Icons: Lucide via @iconify-json/lucide ${pkg.version} (${info.license.spdx}) — https://lucide.dev
(function (g) {
  const SD = (g.SD = g.SD || {});
  SD.iconBodies = ${JSON.stringify(bodies, null, 2)};
})(globalThis);
`;
writeFileSync(join(root, 'web/js/icons.js'), out);
console.log(`Wrote ${Object.keys(bodies).length} icons to web/js/icons.js`);
